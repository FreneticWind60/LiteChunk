package com.frenetic.litechunk.entities;

import com.hivemc.chunker.conversion.encoding.bedrock.base.resolver.BedrockResolvers;
import com.hivemc.chunker.conversion.encoding.java.base.resolver.JavaResolvers;
import com.hivemc.chunker.conversion.intermediate.column.chunk.identifier.ChunkerBlockIdentifier;
import com.hivemc.chunker.nbt.TagType;
import com.hivemc.chunker.nbt.tags.collection.CompoundTag;
import com.hivemc.chunker.nbt.tags.collection.ListTag;
import com.hivemc.chunker.nbt.tags.primitive.DoubleTag;
import com.hivemc.chunker.nbt.tags.primitive.FloatTag;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;

/**
 * Builds the Bedrock actor tag for one Java entity.
 * <p>
 * An actor is an identifier plus the list of component groups that are enabled on it. Bedrock has been data driven
 * since 1.16.100: the identifier alone gives no physics, no collision and nothing to render, which is why an actor
 * written with only {@code identifier} is silently dropped by the game. The groups come from the generated
 * {@link EntityGroupTable}, which is derived from the vanilla behaviour pack.
 * <p>
 * Entities the pack does not know about (dropped items, experience orbs) are the other way round: their
 * {@code definitions} list is empty in a real save, and what makes them work is the payload - the item stack for a
 * drop, the value for an orb.
 * <p>
 * Still missing on purpose: health/attributes, equipment, containers and the variant integers. Those need the item
 * converter and the per-entity enum tables, and they are the next step rather than something to guess at here.
 */
final class BedrockActorBuilder {

    private static final String NAMESPACE = "minecraft:";

    private static final String ITEM = "minecraft:item";
    private static final String EXPERIENCE_ORB = "minecraft:xp_orb";
    private static final String FALLING_BLOCK = "minecraft:falling_block";
    private static final String PRIMED_TNT = "minecraft:tnt";
    private static final String END_CRYSTAL = "minecraft:ender_crystal";

    /** Vanilla gives a dropped item 5 health; it is destroyed when fire, lava or an explosion takes the last point. */
    private static final short ITEM_HEALTH = 5;

    private BedrockActorBuilder() {
    }

    /**
     * @param javaEntity the entity NBT from the Java world.
     * @param uniqueId   the Bedrock unique id to write, generated by the caller so it is unique per world.
     * @return the actor tag, or null when the entity has no usable identifier.
     */
    @Nullable
    static CompoundTag build(CompoundTag javaEntity, long uniqueId) {
        return build(javaEntity, uniqueId, null, null);
    }

    /**
     * @param javaEntity the entity NBT from the Java world.
     * @param uniqueId   the Bedrock unique id to write, generated by the caller so it is unique per world.
     * @param source     resolvers of the Java version that was read, used to translate item stacks.
     * @param target     resolvers of the Bedrock version being written, used to translate item stacks.
     * @return the actor tag, or null when the entity has no usable identifier or cannot be represented.
     */
    @Nullable
    static CompoundTag build(CompoundTag javaEntity, long uniqueId,
                             @Nullable JavaResolvers source, @Nullable BedrockResolvers target) {
        String identifier = EntityIds.toBedrock(javaEntity.getString("id", null));
        if (identifier == null) {
            return null;
        }

        // Paintings, item frames and cushions need data the generic actor shape cannot express (motive, hanging
        // direction, attached block, the half block offset). The engine already has handlers for exactly those, so
        // they are converted there instead of being flattened here.
        CompoundTag delegated = EngineEntities.convert(javaEntity, source, target);
        if (delegated != null) {
            finish(delegated, javaEntity, uniqueId);
            return delegated;
        }

        EntityGroupTable.Row row = EntityGroupTable.of(identifier);
        boolean baby = isBaby(javaEntity);

        List<String> definitions = new ArrayList<>(8);
        // The game only leads with `+<identifier>` for entities its behaviour pack defines. A dropped item is not
        // one of them and a real save stores an empty list for it, so mirroring that avoids handing the game a group
        // name it has never heard of.
        if (row != null) {
            definitions.add("+" + identifier);
            for (String group : row.groups(baby)) {
                // The table stores group names bare (the pack is inconsistent about the namespace).
                definitions.add("+" + NAMESPACE + group);
            }
        }

        CompoundTag actor = new CompoundTag(12);
        actor.put("identifier", identifier);

        // Entity properties (1.21.x): a second state channel next to the component groups, e.g. the climate and sound
        // variant of a cow. Only literal defaults are in the table; anything Molang driven is left for the game.
        if (row != null && row.hasProperties()) {
            actor.put("properties", row.properties());
        }

        // Name, persistence and health: state that cannot be rebuilt from the components.
        EntityTemplate.apply(actor, identifier, javaEntity);

        // What the actor holds and wears. Needs the item resolvers, so it is a no-op when they are unavailable.
        EntityEquipment.apply(actor, javaEntity, source, target);

        // Chests on minecarts and animals.
        EntityContainers.apply(actor, identifier, javaEntity, source, target);

        // Colour, coat and the like: writes the variant integer and, when the pack defines one, the matching group.
        // Runs before the definitions are serialised because it appends to that list.
        EntityVariants.apply(actor, identifier, javaEntity, definitions);

        // Saddle, collar, sitting and the villager's job: also appends groups, so it runs before the serialisation too.
        EntityStates.apply(actor, identifier, javaEntity, definitions);

        actor.put("definitions", ListTag.fromValues(TagType.STRING, definitions));

        if (ITEM.equals(identifier)) {
            CompoundTag item = ItemStacks.convert(itemTag(javaEntity), source, target);
            if (item == null) {
                // An item actor without its stack renders as nothing and is removed by the game on the first tick,
                // so dropping it here is better than writing a record that cannot work.
                return null;
            }
            actor.put("Item", item);
            actor.put("Health", ITEM_HEALTH);
        } else if (EXPERIENCE_ORB.equals(identifier)) {
            // Bedrock keeps the number under a key with a space in it, Java under `Value`, and Java stores it as a
            // short while Bedrock takes an int.
            actor.put("experience value", Math.max(1, intValue(javaEntity, "Value", 1)));
        } else if (FALLING_BLOCK.equals(identifier)) {
            CompoundTag falling = fallingBlock(javaEntity, source, target);
            if (falling == null) {
                // Without its block a falling block actor has nothing to place when it lands.
                return null;
            }
            actor.put("FallingBlock", falling);
        } else if (PRIMED_TNT.equals(identifier)) {
            // Java stores the countdown as `fuse`, Bedrock as `Fuse`. Keep it, otherwise every converted piece of
            // lit TNT restarts its countdown and burns for the full eighty ticks.
            actor.put("Fuse", (short) intValue(javaEntity, "fuse", 80));
        } else if (END_CRYSTAL.equals(identifier)) {
            actor.put("ShowBottom", (byte) (isTrue(javaEntity, "ShowBottom") ? 1 : 0));
        }

        actor.put("Pos", vector(javaEntity.getListValues("Pos", DoubleTag.class, null), 3));
        actor.put("Motion", vector(javaEntity.getListValues("Motion", DoubleTag.class, null), 3));

        List<Float> rotation = javaEntity.getListValues("Rotation", FloatTag.class, null);
        ListTag<FloatTag, Float> rotationTag = new ListTag<>(TagType.FLOAT, 2);
        rotationTag.add(new FloatTag(rotation != null && rotation.size() > 0 ? rotation.get(0) : 0F));
        rotationTag.add(new FloatTag(rotation != null && rotation.size() > 1 ? rotation.get(1) : 0F));
        actor.put("Rotation", rotationTag);

        // Both a drop and an orb carry the tick counter that eventually despawns them, and both formats store it as a
        // short under `Age`. Losing it would reset the five minute timer on every converted world.
        if (ITEM.equals(identifier) || EXPERIENCE_ORB.equals(identifier)) {
            actor.put("Age", (short) Math.max(Short.MIN_VALUE, Math.min(Short.MAX_VALUE,
                    intValue(javaEntity, "Age", 0))));
        }

        actor.put("UniqueID", uniqueId);
        return actor;
    }

    /**
     * Turn the falling block's block into the Bedrock form.
     * <p>
     * Since 1.20.2 Java keeps it in {@code BlockState} as a block tag; older worlds only have the {@code Block} name
     * without any states, so a name-only tag is fed to the same resolver.
     *
     * @param entity the entity tag.
     * @param source resolvers of the Java version that was read.
     * @param target resolvers of the Bedrock version being written.
     * @return the Bedrock block tag, or null when the block is unknown or missing.
     */
    @Nullable
    private static CompoundTag fallingBlock(CompoundTag entity, @Nullable JavaResolvers source,
                                            @Nullable BedrockResolvers target) {
        if (source == null || target == null) {
            return null;
        }
        CompoundTag state = entity.getCompound("BlockState", null);
        if (state == null) {
            String name = entity.getString("Block", null);
            if (name == null) {
                return null;
            }
            state = new CompoundTag(2);
            state.put("Name", name);
        }
        ChunkerBlockIdentifier block = source.readBlock(state);
        if (block == null || block.isAir()) {
            return null;
        }
        return target.writeBlock(block).compoundTag();
    }

    /**
     * @param entity the entity tag.
     * @param name   the field name.
     * @return true when the field holds a non-zero byte.
     */
    private static boolean isTrue(CompoundTag entity, String name) {
        Object value = entity.contains(name) ? entity.get(name).getBoxedValue() : null;
        return value instanceof Number number && number.byteValue() != 0;
    }

    /**
     * Fill in the fields every actor needs but a handler may not have written.
     *
     * @param actor      the actor tag, modified in place.
     * @param javaEntity the Java entity the values come from.
     * @param uniqueId   the id to assign.
     */
    private static void finish(CompoundTag actor, CompoundTag javaEntity, long uniqueId) {
        if (!actor.contains("Pos")) {
            actor.put("Pos", vector(javaEntity.getListValues("Pos", DoubleTag.class, null), 3));
        }
        if (!actor.contains("Motion")) {
            actor.put("Motion", vector(javaEntity.getListValues("Motion", DoubleTag.class, null), 3));
        }
        if (!actor.contains("Rotation")) {
            List<Float> rotation = javaEntity.getListValues("Rotation", FloatTag.class, null);
            ListTag<FloatTag, Float> rotationTag = new ListTag<>(TagType.FLOAT, 2);
            rotationTag.add(new FloatTag(rotation != null && rotation.size() > 0 ? rotation.get(0) : 0F));
            rotationTag.add(new FloatTag(rotation != null && rotation.size() > 1 ? rotation.get(1) : 0F));
            actor.put("Rotation", rotationTag);
        }
        actor.put("UniqueID", uniqueId);
    }

    /**
     * Java names the stack {@code Item}; the lower case spelling is read as well in case a future version renames it.
     */
    @Nullable
    private static CompoundTag itemTag(CompoundTag entity) {
        CompoundTag item = entity.getCompound("Item", null);
        return item != null ? item : entity.getCompound("item", null);
    }

    /**
     * Java stores several counters as shorts on some entities and ints on others, and reading them with
     * {@code getInt} throws a {@link ClassCastException} on the short ones.
     *
     * @param entity       the entity tag.
     * @param name         the field name.
     * @param defaultValue value to use when the field is missing or not a number.
     * @return the field as an int.
     */
    private static int intValue(CompoundTag entity, String name, int defaultValue) {
        Object value = entity.contains(name) ? entity.get(name).getBoxedValue() : null;
        return value instanceof Number number ? number.intValue() : defaultValue;
    }

    /**
     * Java marks babies with {@code IsBaby} on most mobs and with a negative {@code Age} on the rest.
     *
     * @param entity the Java entity NBT.
     * @return true when the actor should use the baby component groups.
     */
    private static boolean isBaby(CompoundTag entity) {
        if (entity.contains("IsBaby")) {
            return entity.getByte("IsBaby", (byte) 0) != 0;
        }
        // Age is a short on some entities and an int on others, and getInt would cast. Read it as a number instead.
        Object age = entity.contains("Age") ? entity.get("Age").getBoxedValue() : null;
        return age instanceof Number number && number.doubleValue() < 0;
    }

    /**
     * Java stores Pos/Motion as doubles, Bedrock as floats.
     */
    private static ListTag<FloatTag, Float> vector(@Nullable List<Double> values, int size) {
        ListTag<FloatTag, Float> tag = new ListTag<>(TagType.FLOAT, size);
        for (int index = 0; index < size; index++) {
            double value = values != null && values.size() > index ? values.get(index) : 0D;
            tag.add(new FloatTag((float) value));
        }
        return tag;
    }
}
