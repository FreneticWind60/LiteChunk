import java.util.Properties

plugins {
    id("com.android.application")
}

// Release signing lives outside the build script: keystore.properties + keystore/*.jks are the only
// copy of the key, so they stay out of version control and the project still configures (and still
// produces an unsigned release) on a machine that does not have them.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val canSignRelease = keystorePropertiesFile.exists()

android {
    namespace = "com.frenetic.litechunk"
    compileSdk = 37
    buildToolsVersion = "37.0.0"

    defaultConfig {
        applicationId = "com.frenetic.litechunk"
        minSdk = 27
        targetSdk = 37
        // 1.21.0 build1
        // versionCode = major*10^8 + minor*10^6 + patch*10^4 + build*100 + stage,
        //   stage = 1..49 for a preview ("prN"), 50 for the released build.
        //   -> 1.21.0 build1 pr1 = 121_000_101, 1.21.0 build1 = 121_000_150, 1.21.0 build2 = 121_000_250.
        // The 10^8 scale (rather than 10^7) is deliberate: the first two previews shipped as
        // 12_100_501 / 12_100_502 under an older encoding, and a release has to be installable over
        // them on any device that still has one.
        versionCode = 121_000_150
        versionName = "1.21.0 build1"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    buildFeatures {
        viewBinding = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    signingConfigs {
        if (canSignRelease) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                enableV1Signing = true
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (canSignRelease) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    packaging {
        resources {
            excludes += setOf("META-INF/*.kotlin_module", "DebugProbesKt.bin")
        }
    }
}

// assets/chunker.jar is generated by :engine:engineDex. Declared as a plain asset it would
// give Gradle no ordering guarantee, so `:app:assembleDebug` on its own could package the
// previous dex -- a silent stale-engine build. Every task that reads the assets directory has to
// wait for it: the merge tasks, and lint's model writers (Gradle validates that the asset really
// is produced by a task once engineDex declares it as an output).
tasks.matching {
    (it.name.startsWith("merge") && it.name.contains("Assets", ignoreCase = true)) ||
        it.name.contains("lint", ignoreCase = true)
}.configureEach {
    dependsOn(":engine:engineDex")
}

